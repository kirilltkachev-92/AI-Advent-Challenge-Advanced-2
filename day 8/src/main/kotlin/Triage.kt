import kotlinx.serialization.Serializable

/**
 * Результат триажа обращения в поддержку мобильного банка:
 * категория из фиксированного списка + самооценка уверенности модели [0;1]
 * + причина одним русским предложением. Валидность (категория в белом списке,
 * confidence в диапазоне) проверяет роутер при оборонительном парсинге.
 */
@Serializable
data class Triage(
    val category: String,
    val confidence: Double,
    val reason: String,
) {
    companion object {
        /** Белый список категорий; всё вне его — невалидный ответ модели. */
        val CATEGORIES: Set<String> = setOf(
            "карта_заблокирована",
            "платёж_не_прошёл",
            "кредит_вопрос",
            "мошенничество",
            "приложение_баг",
            "другое",
        )
    }
}
