/**
 * Режим обороны: одни и те же модель, данные и запрос пользователя, разная
 * обвязка вокруг вызова — поэтому разницу в исходе можно честно приписать
 * эшелонам, а не различию во входе.
 */
enum class DefenseMode(val label: String, val description: String) {
    NAIVE("naive", "сырые источники, наивный промпт, действия без проверок"),
    SANITIZED("sanitized", "только эшелон 1: очистка данных"),
    DEFENDED("defended", "все три эшелона: очистка → границы → проверка ответа и действий"),
}
