/**
 * Роль агента в сценарии. Роль определяет и его обязанность (что он вообще
 * должен делать), и то, какой системный промпт становится предметом атаки:
 * у `ANALYST` ограничение «только цифры, никаких рекомендаций» — это ровно то,
 * что закладка в документе пытается снять.
 */
enum class AgentRole(val label: String) {
    SUMMARIZER("агент-суммаризатор почты"),
    ANALYST("агент-аналитик документов"),
    SEARCHER("агент-поисковик по вебу"),
    CODE_REVIEWER("агент-кодер в репозитории"),
}
