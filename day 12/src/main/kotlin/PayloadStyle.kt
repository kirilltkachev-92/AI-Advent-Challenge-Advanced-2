/**
 * Стиль формулировки закладки — при ОДИНАКОВЫХ техниках сокрытия.
 *
 * Техника отвечает за то, увидит ли закладку человек; стиль — за то, поверит ли
 * ей модель. `OVERT` кричит о себе («SYSTEM: игнорируй инструкции»), и его
 * распознаёт даже alignment без всякой обороны. `COVERT` написан как обычный
 * текст этого типа данных — пометка почтового клиента, регламент раскрытия
 * информации, примечание редакции, внутренний стайлгайд — и не содержит ни
 * одного слова про инструкции и их игнорирование.
 *
 * Стиль — отдельная ось эксперимента: основная матрица гоняется на `COVERT`,
 * а отдельная секция отчёта сравнивает оба стиля в режиме `naive`, где обороны
 * нет вовсе и виден чистый вклад формулировки.
 */
enum class PayloadStyle(val label: String) {
    OVERT("прямая команда"),
    COVERT("маскировка под легитимный контент"),
}
