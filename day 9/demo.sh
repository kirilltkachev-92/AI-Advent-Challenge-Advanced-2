#!/usr/bin/env bash
# Демо для видео: декомпозиция инференса — монолит vs конвейер из трёх этапов (day 9).
# Полный прогон 16 кейсов — до ~64 LLM-вызовов, поэтому шаг 2 показывает
# закешированный output/report.md, если он уже есть (иначе запускает прогон).
# DEMO_PAUSE=<сек> — пауза после каждого шага (для записи видео; по умолчанию 0).
set -euo pipefail
cd "$(dirname "$0")"

pause() { sleep "${DEMO_PAUSE:-0}"; }

echo "── 1. Шумная претензия: три этапа конвейера против одного монолита ──"
./run.sh one "два раза сняли за кофе 380 рэ, чек есть, верните"
echo
pause

echo "── 2. Полный прогон 16 кейсов A vs B (или кешированный отчёт) ───────"
if [[ -f output/report.md ]]; then
  cat output/report.md
else
  ./run.sh run
  cat output/report.md
fi
echo
pause

echo "── 3. Итоги: точность, расхождения с кодовой проверкой, цена ────────"
sed -n '/^## Итоги/,$p' output/report.md
