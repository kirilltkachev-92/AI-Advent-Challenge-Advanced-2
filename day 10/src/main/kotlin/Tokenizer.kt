/**
 * Токенизатор micro-model: lowercase, ё→е, вся пунктуация → пробелы, разбиение
 * по пробелам, затем лёгкий стемминг — срезание одного частотного русского
 * окончания (без библиотек). Стем срезается только если остаётся ≥ 3 символов:
 * «карту/карты/картой» → «карт», «переведите/переведи» → «перевед»,
 * «оператором/оператора» → «оператор». Это сознательно грубый стеммер:
 * разные основы («перевод» vs «перевести») не склеиваются — покрытие форм
 * обеспечивают сами примеры в IntentSeeds.
 */
object Tokenizer {
    /** Частотные окончания, от длинных к коротким; срезается ровно одно. */
    private val SUFFIXES = listOf(
        "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
        "ешь", "ете", "ите", "ая", "ой", "ей", "ый", "ий",
        "ам", "ям", "ом", "ем", "ов", "ев", "ах", "ях",
        "у", "ю", "а", "я", "ы", "и", "е", "о", "ь", "й",
    ).sortedByDescending { it.length }

    /** Текст → список стеммированных токенов. */
    fun tokenize(text: String): List<String> =
        text.lowercase()
            .replace('ё', 'е')
            .map { if (it.isLetterOrDigit()) it else ' ' }
            .joinToString("")
            .split(' ')
            .filter { it.isNotBlank() }
            .map(::stem)

    /** Срезает одно окончание, если основа остаётся не короче 3 символов. */
    fun stem(word: String): String {
        for (suffix in SUFFIXES) {
            if (word.length - suffix.length >= 3 && word.endsWith(suffix)) {
                return word.dropLast(suffix.length)
            }
        }
        return word
    }
}
