/**
 * Интенты запросов клиента в поддержку банка — единый enum для обоих уровней:
 * micro-model классифицирует в него напрямую, LLM-fallback обязан вернуть
 * ровно одно из этих имён (иначе формат считается невалидным).
 * UNSURE интентом НЕ является — это статус маршрутизации micro-model.
 */
enum class Intent(val label: String) {
    BALANCE("баланс и остаток по счёту"),
    CARD_BLOCK("блокировка карты (утеря, кража, компрометация)"),
    REFUND_CLAIM("возврат денег / спорное списание"),
    TRANSFER("перевод денег"),
    PIN_CHANGE("смена или восстановление пин-кода"),
    OPERATOR("соединить с живым оператором"),
}
